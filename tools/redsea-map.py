# Regenerates the Red Sea report's lane map land: python3 tools/redsea-map.py land-50m.json > assets/js/redsea-map.js
# (land-50m.json from https://cdn.jsdelivr.net/npm/world-atlas@2/, Natural Earth, public domain)
# Plain equirectangular, 22°W to 135°E and 50°N to 40°S, viewBox 0 0 1000 573; redsea-report.js projects the
# lanes with the same numbers (MAP there).
import json, sys

LON0, LON1, LAT0, LAT1 = -22.0, 135.0, 50.0, -40.0
K = 1000 / (LON1 - LON0)
W, H = 1000, round((LAT0 - LAT1) * K)

def proj(lon, lat): return ((lon - LON0) * K, (LAT0 - lat) * K)

def decode(path):
    t = json.load(open(path))
    sx, sy = t["transform"]["scale"]; tx, ty = t["transform"]["translate"]
    arcs = []
    for a in t["arcs"]:
        x = y = 0; pts = []
        for dx, dy in a:
            x += dx; y += dy; pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    def arc(i): return arcs[i] if i >= 0 else arcs[~i][::-1]
    def ring(r):
        out = []
        for i in r:
            p = arc(i); out.extend(p if not out else p[1:])
        return out
    for g in t["objects"]["land"]["geometries"]:
        for poly in (g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]]):
            for r in poly: yield ring(r)

d = []
for pts in decode(sys.argv[1]):
    if any(x > 170 for x, _ in pts) and any(x < -170 for x, _ in pts):  # straddles the 180° meridian (Fiji): unwrap it east
        pts = [(x + 360 if x < -170 else x, y) for x, y in pts]
    pp = [proj(x, y) for x, y in pts]
    if all(px < 0 for px, _ in pp) or all(px > W for px, _ in pp) or all(py < 0 for _, py in pp) or all(py > H for _, py in pp): continue
    pp = [(min(max(px, -2), W + 2), min(max(py, -2), H + 2)) for px, py in pp]
    keep = [pp[0]]
    for q in pp[1:]:
        if abs(q[0] - keep[-1][0]) + abs(q[1] - keep[-1][1]) > 0.9: keep.append(q)
    if len(keep) < 3: continue
    xs = [q[0] for q in keep]; ys = [q[1] for q in keep]
    if max(xs) - min(xs) < 1.2 and max(ys) - min(ys) < 1.2: continue
    d.append("M" + "L".join("%.1f %.1f" % q for q in keep) + "Z")

print("/* Generated by tools/redsea-map.py from Natural Earth 1:50m land (public domain); don't edit by hand.\n"
      "   Land for the Red Sea report's lane map, equirectangular %g..%g°E, %g..%g°N, viewBox 0 0 %d %d. */" % (LON0, LON1, LAT1, LAT0, W, H))
print("window.RS_LAND = %s;" % json.dumps("".join(d)))
